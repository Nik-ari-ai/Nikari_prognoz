"""Календарь месяцев для проверочного эксперимента.

Используются только номер месяца и число календарных дней: они известны
заранее. Производственный календарь исключён: в исходном проекте его
константы не имели проверяемых дат публикации. Переносы выходных
требуют согласования с датой принятия соответствующего решения. Для его возврата нужен отдельный источник.
"""

import pandas as pd


def build_calendar_features_table(months):
    """Собрать детерминированные признаки месяцев без внешних данных."""
    rows = []
    for month in months:
        rows.append({
            "month": month,
            "month_number": month.month,
            "days_in_month": month.days_in_month,
        })
    return pd.DataFrame(rows)
